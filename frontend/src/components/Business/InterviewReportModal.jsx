/* ─────────────────────────── helpers ─────────────────────────── */

const sc = (n) => {
  const v = Number(n) || 0;
  if (v >= 75) return '#16a34a';
  if (v >= 50) return '#d97706';
  return '#dc2626';
};

const ScorePill = ({ value }) => (
  <span style={{
    display: 'inline-block',
    background: `${sc(value)}18`,
    color: sc(value),
    border: `1px solid ${sc(value)}40`,
    borderRadius: 9999,
    padding: '2px 10px',
    fontSize: 12,
    fontWeight: 700,
  }}>
    {Number(value) || 0}/100
  </span>
);

const SectionCard = ({ title, children, accent = '#3b82f6' }) => (
  <div style={{
    background: '#fff',
    borderRadius: 12,
    border: '1px solid #e2e8f0',
    overflow: 'hidden',
    marginBottom: 16,
  }}>
    <div style={{
      background: `${accent}0d`,
      borderBottom: `2px solid ${accent}30`,
      padding: '10px 18px',
    }}>
      <span style={{ fontWeight: 700, fontSize: 14, color: accent }}>{title}</span>
    </div>
    <div style={{ padding: '14px 18px' }}>{children}</div>
  </div>
);

const BulletList = ({ items, color = '#475569', icon = '•' }) => {
  const arr = (items || []).filter(Boolean);
  if (!arr.length) return <p style={{ color: '#94a3b8', fontSize: 13 }}>None listed.</p>;
  return (
    <ul style={{ margin: 0, padding: 0, listStyle: 'none' }}>
      {arr.map((item, i) => (
        <li key={i} style={{
          display: 'flex', gap: 8, fontSize: 13, color,
          lineHeight: 1.55, marginBottom: 6, alignItems: 'flex-start',
        }}>
          <span style={{ flexShrink: 0, marginTop: 2, fontWeight: 700 }}>{icon}</span>
          <span>{item}</span>
        </li>
      ))}
    </ul>
  );
};

const Tag = ({ label, color }) => (
  <span style={{
    background: `${color}15`,
    color,
    border: `1px solid ${color}35`,
    borderRadius: 6,
    padding: '3px 10px',
    fontSize: 12,
    fontWeight: 600,
    display: 'inline-block',
    margin: '2px',
  }}>
    {label}
  </span>
);

/* ─────────────────── resume PDF download ────────────────────── */

const downloadResumePdf = (candidateName, resume) => {
  const doc = new jsPDF();
  let y = 18;

  const safeText = (txt) => String(txt || '').replace(/[^\x00-\x7F]/g, '?');
  const section = (title, accent) => {
    if (y > 265) { doc.addPage(); y = 18; }
    doc.setFillColor(...accent);
    doc.rect(14, y - 1, 182, 8, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(255, 255, 255);
    doc.text(safeText(title), 16, y + 5);
    doc.setTextColor(0, 0, 0);
    y += 12;
  };
  const line = (txt, indent = 14, bold = false) => {
    if (!txt) return;
    if (y > 278) { doc.addPage(); y = 18; }
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(10);
    const lines = doc.splitTextToSize(safeText(txt), 196 - indent);
    doc.text(lines, indent, y);
    y += lines.length * 5 + 2;
  };

  // Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text(safeText(candidateName || 'Candidate Resume'), 14, y);
  y += 12;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 100, 100);
  doc.text('Generated by Interview Genius Platform', 14, y);
  doc.setTextColor(0, 0, 0);
  y += 10;

  const edu = resume?.Education || [];
  const exp = resume?.Experience || [];
  const proj = resume?.Projects || [];
  const skills = resume?.Skills || [];

  if (edu.length) {
    section('EDUCATION', [30, 64, 175]);
    edu.forEach((e) => line(`• ${e}`, 16));
    y += 4;
  }
  if (exp.length) {
    section('EXPERIENCE', [21, 128, 61]);
    exp.forEach((e) => line(`• ${e}`, 16));
    y += 4;
  }
  if (proj.length) {
    section('PROJECTS', [124, 45, 18]);
    proj.forEach((p) => line(`• ${p}`, 16));
    y += 4;
  }
  if (skills.length) {
    section('SKILLS', [88, 28, 135]);
    const chunks = [];
    for (let i = 0; i < skills.length; i += 6) chunks.push(skills.slice(i, i + 6).join('  |  '));
    chunks.forEach((c) => line(c, 16));
  }

  doc.save(`${(candidateName || 'candidate').replace(/\s+/g, '-').toLowerCase()}-resume.pdf`);
};

