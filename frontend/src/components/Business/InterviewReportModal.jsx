  const atsScore = applicationData?.ats_score ?? session?.ats_score ?? 0;

  useEffect(() => {
    if (!sessionId) {
      setError('No AI interview session linked to this application.');
      setLoading(false);
      return;
    }
    const load = async () => {
      try {
        const res = await fetch(`${PYTHON_API_URL}/api/interview-session/${encodeURIComponent(sessionId)}`);
        const data = await res.json();
        if (!res.ok) throw new Error(data.error || 'Failed to load interview session');
        setSession(data);
      } catch (err) {
        setError(err.message || 'Failed to load interview report.');
      } finally {
        setLoading(false);
      }
    };
    load();
  }, [sessionId]);

